import { test, expect } from '@playwright/test'
import { fixtures } from '../src/demo/fixtures'

for (const width of [375, 1440]) test(`板块职责、协议清单和双向跳转 ${width}px`, async ({ page }, testInfo) => {
  await page.setViewportSize({ width, height: 1000 })
  await page.emulateMedia({ colorScheme: width === 375 ? 'dark' : 'light', reducedMotion: 'reduce' })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const data = fixtures(Date.now()), n = data.nodes[0], user = data.users[0]
  n.inbounds = Array.from({ length: 19 }, (_, i) => ({ tag: `vmess-${i}`, protocol: 'vmess', port: 23000 + i, active: true, started_at: n.quality.started_at!, upload_bytes: '1024', download_bytes: '4096' }))
  n.inbounds.push({ ...n.inbounds[0], tag: 'retired-inbound', active: false })
  n.total_inbounds = 19
  await page.addInitScript(data => sessionStorage.setItem('sbctl-f0-synthetic-state-v1', JSON.stringify({ ...data, requests: {}, signedIn: true })), data)
  await page.goto('/')
  await expect(page.getByRole('region', { name: '板块入口' })).toBeVisible()
  await expect(page.getByRole('button', { name: /选择统计日期/ })).toHaveCount(0)
  if (width === 375) await page.getByRole('button', { name: '打开导航', exact: true }).click()
  const nav = page.getByRole('navigation', { name: width === 375 ? '移动导航' : '主导航' })
  for (const label of ['资源管理', '用量分析', '运维']) await expect(nav.getByText(label, { exact: true })).toBeVisible()
  await nav.getByRole('link', { name: '节点与协议', exact: true }).click()
  await expect(page.getByRole('heading', { name: '节点与协议' })).toBeVisible()
  await page.getByRole('textbox', { name: '搜索节点名称或编号…' }).fill(n.name)
  await expect(page.locator('#main-content')).toContainText('19 个入口')
  await expect(page.locator('#main-content')).not.toContainText('受管用户累计')
  await page.getByRole('link', { name: new RegExp(n.name) }).filter({ visible: true }).first().click()
  await expect(page.getByRole('heading', { name: 'sing-box 管理' })).toBeVisible()
  const inventory = page.getByRole('region', { name: '协议入口', exact: true })
  await expect(inventory).toContainText('19 个当前入口、1 种协议')
  await expect(inventory).not.toContainText('retired-inbound')
  await expect(page.getByLabel('流量筛选')).toHaveCount(0)
  await inventory.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(inventory).toContainText('2 / 2 页')
  await inventory.getByRole('textbox', { name: '搜索协议入口' }).fill('23018')
  await expect(inventory).toContainText('vmess-18')
  await expect(inventory).toContainText('共 1 条记录')
  await inventory.getByRole('textbox', { name: '搜索协议入口' }).fill('not-found')
  await expect(inventory.getByRole('status')).toContainText('没有匹配的协议入口')
  await inventory.getByRole('button', { name: '清除筛选' }).click()
  await page.evaluate(() => window.scrollTo(0, 0))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(`node-workspace-${width}.png`), fullPage: true })
  await page.getByRole('button', { name: '更新绑定', exact: true }).click()
  await page.getByRole('link', { name: '返回节点管理', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/nodes/${n.id}$`))
  await page.getByRole('link', { name: '查看节点流量', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '筛选流量节点' })).toContainText(n.name)
  await expect(page.getByLabel('流量筛选')).toBeVisible()
  await page.getByRole('textbox', { name: '搜索流量记录' }).fill('vmess')
  await page.getByRole('link', { name: `管理节点：${n.name}` }).click()
  await expect(page).toHaveURL(new RegExp(`/nodes/${n.id}$`))
  await expect(page.getByRole('textbox', { name: '搜索协议入口' })).toHaveValue('')
  await page.goto(`/users/${user.id}`)
  await expect(page.getByRole('heading', { name: '订阅交付' })).toBeVisible()
  await expect(page.locator('#main-content')).not.toContainText('已记录累计')
  await expect(page.getByRole('link', { name: '查看用户流量' })).toHaveCount(0)
  await page.goto('/settings')
  await expect(page.getByRole('heading', { name: '界面设置' })).toBeVisible()
  await expect(page.getByText('0.2.0', { exact: true })).toHaveCount(0)
  expect(errors).toEqual([])
})

test('尚未同步的节点不会显示零入口为实际配置', async ({ page }) => {
  const data = fixtures(Date.now()), n = data.nodes[0], pending = data.nodes[1]
  n.status = 'degraded'; n.live_fresh = false
  n.inbounds = []; n.quality.freshness = 'unknown'; n.quality.sampled_at = null; n.quality.synced_at = null
  pending.status = 'offline'; pending.agent_state = 'unregistered'; pending.agent_last_seen = null; pending.live_fresh = false
  await page.addInitScript(data => sessionStorage.setItem('sbctl-f0-synthetic-state-v1', JSON.stringify({ ...data, requests: {}, signedIn: true })), data)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/nodes')
  const search = page.getByRole('textbox', { name: '搜索节点名称或编号…' })
  await search.fill(n.name)
  const row = page.getByRole('row').filter({ hasText: n.name })
  await expect(row).toContainText('需关注')
  await expect(row).toContainText('管理通道在线')
  await expect(row).toContainText('新鲜度未知')
  await expect(row).toContainText('暂无实时采样')
  await search.fill(pending.name)
  const pendingRow = page.getByRole('row').filter({ hasText: pending.name })
  await expect(pendingRow.getByText('待登记', { exact: true })).toBeVisible()
  await page.goto(`/nodes/${n.id}`)
  const inventory = page.getByRole('region', { name: '协议入口', exact: true })
  await expect(inventory).toContainText('尚未收到入口快照')
  await expect(inventory).not.toContainText('0 个当前入口')
})

test('已有节点绑定更新后保留结果并返回当前节点', async ({ page }) => {
  await page.goto('/nodes/sg-01/setup')
  await page.getByRole('button', { name: '检查连接与容器', exact: true }).click()
  await expect(page.getByText('实际运行信息', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '接管后的容器名称', exact: true }).fill('sing-box-updated')
  await page.getByRole('checkbox', { name: '我确认接管此节点，并接受必要时的短暂重连。' }).check()
  await page.getByRole('button', { name: '确认更新绑定', exact: true }).click()
  await expect(page.getByRole('heading', { name: '节点已接入' })).toBeVisible()
  await page.getByRole('link', { name: '查看节点详情' }).click()
  await expect(page).toHaveURL(/\/nodes\/sg-01$/)
  await expect(page.getByRole('region', { name: 'sing-box 管理' })).toContainText('sing-box-updated')
})
