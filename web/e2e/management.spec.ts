test('批量归档仅选择已撤销用户', async ({ page }) => {
  const data = fixtures(Date.now())
  data.users = data.users.slice(0, 3); data.operations = []
  data.users.forEach((u, i) => { u.status = i < 2 ? 'disabled' : 'active'; u.subscription_state = i < 2 ? 'revoked' : 'published'; u.archived = false })
  await page.addInitScript(data => { if (!sessionStorage.getItem('sbctl-f0-synthetic-state-v1')) sessionStorage.setItem('sbctl-f0-synthetic-state-v1', JSON.stringify({ ...data, requests: {}, signedIn: true })) }, data)
  await page.goto('/users')
  await page.getByRole('button', { name: '选择本页可归档用户', exact: true }).click()
  await page.getByRole('button', { name: '归档所选 2 位', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toContainText(data.users[2].display_name)
  await page.getByRole('button', { name: '确认归档', exact: true }).click()
  await expect(page.getByText('共 1 条记录')).toBeVisible()
  await page.getByRole('combobox', { name: '用户归档范围' }).click()
  await page.getByRole('option', { name: '已归档用户', exact: true }).click()
  await expect(page.getByText('共 2 条记录')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('combobox', { name: '用户归档范围' })).toContainText('已归档用户')
  await page.getByRole('button', { name: '选择本页可归档用户', exact: true }).click()
  await page.getByRole('button', { name: '恢复归档', exact: true }).filter({ visible: true }).first().click()
  await expect(page.getByRole('dialog')).toContainText(data.users[0].id)
  await expect(page.getByRole('dialog')).toContainText(data.users[1].id)
  await page.getByRole('button', { name: '确认恢复', exact: true }).click()
  await expect(page.getByText('共 0 条记录')).toBeVisible()
  await page.getByRole('combobox', { name: '用户归档范围' }).click()
  await page.getByRole('option', { name: '未归档用户', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('combobox', { name: '用户归档范围' })).toContainText('未归档用户')
  await expect(page.getByText('共 3 条记录')).toBeVisible()
})

test('生产管理页面显示版本冲突并重试原节点任务', async ({ page }) => {
  const data = fixtures(Date.now()), node = data.nodes[0], management = createNodeManagementDemo(() => data)
  let retries = 0, changes = 0
  const job = { id: 'njob_test_retry', node_id: node.id, kind: 'check', state: 'failed', result: null, error_code: 'SSH_FAILED', message: '节点连接失败，请恢复后重试', created_at: new Date().toISOString(), updated_at: new Date().toISOString() }
  await page.route('**/api/v1/**', async route => {
    const r = route.request(), path = new URL(r.url()).pathname.replace('/api/v1', '')
    if (path === '/session') return route.fulfill({ json: { admin_id: 'test', display_name: '测试', csrf_token: 'test-csrf' } })
    if (path === `/nodes/${node.id}`) return route.fulfill({ json: node })
    if (path === '/groups') return route.fulfill({ json: data.groups })
    if (path === `/nodes/${node.id}/jobs`) return route.fulfill({ json: [job] })
    if (path === `/node-jobs/${job.id}/retry`) {
      expect(r.headers()['x-csrf-token']).toBe('test-csrf'); retries++; job.state = 'completed'; job.message = '检查恢复成功'
      return route.fulfill({ status: 202, json: { job_id: job.id } })
    }
    if (path === '/node-jobs' && r.postDataJSON().kind === 'protocol_change') {
      changes++
      return route.fulfill({ status: 409, json: { code: 'STALE_REVISION', message: '协议配置已变化，请重新读取' } })
    }
    const response = await management(new Request(r.url(), { method: r.method(), headers: r.headers(), ...(r.postData() ? { body: r.postData()! } : {}) }), path)
    return response ? route.fulfill({ status: response.status, contentType: 'application/json', body: await response.text() }) : route.fulfill({ status: 404, json: {} })
  })
  await page.goto(`http://127.0.0.1:14186/nodes/${node.id}`)
  const region = page.getByRole('region', { name: '协议入口', exact: true })
  await region.getByRole('button', { name: '读取协议配置', exact: true }).click()
  await region.getByRole('button', { name: '编辑', exact: true }).filter({ visible: true }).first().click()
  await page.getByLabel('监听端口', { exact: true }).fill('24000')
  await page.getByRole('button', { name: '确认编辑', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('协议配置已变化，请重新读取')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  const tasks = page.getByRole('region', { name: '节点管理任务' })
  await tasks.getByRole('button', { name: '重试原任务', exact: true }).click()
  await expect(tasks).toContainText('检查恢复成功')
  expect(retries).toBe(1); expect(changes).toBe(1)
})

